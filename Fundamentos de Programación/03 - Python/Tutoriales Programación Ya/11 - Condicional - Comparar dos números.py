num1=int(input("Ingrese el primer número: "))
num2=int(input("Ingrese el segundo número: "))

if num1>num2:
    print("La suma es: ")
    suma=num1+num2
    print(suma)
    print("La resta es: ")
    resta=num1-num2
    print(resta)
    
else:
    print("La multiplicación es: ")
    multiplicacion=num1*num2
    print(multiplicacion)
    print("La división es: ")
    division=num1/num2
    print(division)